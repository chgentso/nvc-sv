architecture test of vhdl_island_clkwatch1 is
    signal clk, rst, en, fclk : std_logic := '0';
    signal q_f : unsigned(7 downto 0);
    signal q_a, q_b, q_data, q_gate, q_div : unsigned(7 downto 0);
    signal lvl, hi : std_logic;
begin
    u_a : entity work.vhdl_island_clkwatch1_cnt
        port map (clk => clk, rst => rst, q => q_a);
    u_b : entity work.vhdl_island_clkwatch1_cnt
        port map (clk => clk, rst => '0', q => q_b);
    u_f : entity work.vhdl_island_clkwatch1_cnt
        port map (clk => fclk, rst => '0', q => q_f);
    u_data : entity work.vhdl_island_clkwatch1_data
        port map (clk => clk, lvl => lvl, cnt => q_data, hi => hi);
    u_gate : entity work.vhdl_island_clkwatch1_gate
        port map (clk => clk, en => en, q => q_gate);
    u_div : entity work.vhdl_island_clkwatch1_div
        port map (clk => clk, q => q_div);

    p_stim : process is
        alias dut_clk is << signal .vhdl_island_clkwatch1.fclk : std_logic >>;

        procedure tick is
        begin
            clk <= '1';
            wait for 5 ns;
            assert hi = '1' report "hi must follow clk high";
            clk <= '0';
            wait for 5 ns;
            assert hi = '0' report "hi must follow clk low";
        end procedure;
    begin
        wait for 1 ns;
        -- Five edges, gate closed
        for i in 1 to 5 loop
            tick;
        end loop;
        assert q_a = 5 report "q_a=5 expected" severity failure;
        assert q_b = 5 report "q_b=5 expected" severity failure;
        assert q_data = 5 report "q_data=5 expected" severity failure;
        assert lvl = '1' report "clock read by the body must be high"
            severity failure;
        assert q_gate = 0 report "gated count must stay 0" severity failure;
        assert q_div = 3 report "q_div=3 expected" severity failure;

        -- Open the gate: edges now clock the gated register
        en <= '1';
        wait for 1 ns;
        for i in 1 to 4 loop
            tick;
        end loop;
        assert q_gate = 4 report "q_gate=4 expected" severity failure;
        assert q_a = 9 report "q_a=9 expected" severity failure;
        assert q_div = 5 report "q_div=5 expected" severity failure;

        -- Asynchronous reset of one counter between two edges
        rst <= '1';
        wait for 1 ns;
        assert q_a = 0 report "async reset must clear q_a" severity failure;
        assert q_b = 9 report "q_b must be unaffected" severity failure;
        tick;
        assert q_a = 0 report "q_a held in reset" severity failure;
        assert q_b = 10 report "q_b=10 expected" severity failure;
        rst <= '0';
        wait for 1 ns;
        tick;
        assert q_a = 1 report "q_a=1 expected" severity failure;

        -- Force a clock that nothing else drives: only its register counts
        dut_clk <= force '1';
        wait for 1 ns;
        assert q_f = 1 report "forced clock must clock q_f" severity failure;
        assert q_a = 1 report "q_a must not see the forced edge"
            severity failure;
        dut_clk <= force '0';
        wait for 1 ns;
        dut_clk <= force '1';
        wait for 1 ns;
        assert q_f = 2 report "second forced edge" severity failure;
        dut_clk <= release;
        wait for 1 ns;
        tick;
        assert q_a = 2 report "q_a=2 expected" severity failure;
        assert q_b = 12 report "q_b=12 expected" severity failure;
        assert q_f = 2 report "q_f must hold after release" severity failure;
        assert q_data = 12 report "q_data=12 expected" severity failure;

        report "done";
        wait;
    end process;
end architecture;
