-- A signal used only as a flip-flop clock needs no island input watch, the
-- domain clock watch samples it.  The values seen by the registers must not
-- change when the clock is read as data, gates another clock, is driven from
-- inside an island, resets asynchronously or is forced.

library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

entity vhdl_island_clkwatch1_cnt is
    port (clk, rst : in std_logic;
          q        : out unsigned(7 downto 0));
end entity;

architecture rtl of vhdl_island_clkwatch1_cnt is
    signal r : unsigned(7 downto 0) := (others => '0');
begin
    -- Clock only used as the edge trigger, asynchronous reset
    p_ff : process (clk, rst) is
    begin
        if rst = '1' then
            r <= (others => '0');
        elsif rising_edge(clk) then
            r <= r + 1;
        end if;
    end process;
    q <= r;
end architecture;

library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

-- Clock also read as data by the flip-flop body and by a combinational process
entity vhdl_island_clkwatch1_data is
    port (clk : in std_logic;
          lvl : out std_logic;
          cnt : out unsigned(7 downto 0);
          hi  : out std_logic);
end entity;

architecture rtl of vhdl_island_clkwatch1_data is
    signal c : unsigned(7 downto 0) := (others => '0');
begin
    p_ff : process (clk) is
    begin
        if rising_edge(clk) then
            c <= c + 1;
            lvl <= clk;
        end if;
    end process;
    cnt <= c;
    hi <= clk;
end architecture;

library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

-- Gated clock: the derived clock is driven by a combinational process
entity vhdl_island_clkwatch1_gate is
    port (clk, en : in std_logic;
          q       : out unsigned(7 downto 0));
end entity;

architecture rtl of vhdl_island_clkwatch1_gate is
    signal gclk : std_logic;
    signal r    : unsigned(7 downto 0) := (others => '0');
begin
    gclk <= clk and en;

    p_ff : process (gclk) is
    begin
        if rising_edge(gclk) then
            r <= r + 1;
        end if;
    end process;
    q <= r;
end architecture;

library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

-- Clock divider (clock generated by a register) feeding a second domain
entity vhdl_island_clkwatch1_div is
    port (clk : in std_logic;
          q   : out unsigned(7 downto 0));
end entity;

architecture rtl of vhdl_island_clkwatch1_div is
    signal dclk : std_logic := '0';
    signal r    : unsigned(7 downto 0) := (others => '0');
begin
    p_div : process (clk) is
    begin
        if rising_edge(clk) then
            dclk <= not dclk;
        end if;
    end process;

    p_ff : process (dclk) is
    begin
        if rising_edge(dclk) then
            r <= r + 1;
        end if;
    end process;
    q <= r;
end architecture;

